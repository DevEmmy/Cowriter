import assert from "node:assert";
import { levenshtein, localGuard, quoteInText, hashOf, bibleText } from "../src/lib/ai/story";
assert.equal(levenshtein("adaeze", "adaeze"), 0);
assert.equal(levenshtein("mara", "mare"), 1);
assert.equal(levenshtein("adaeze", "adeaze"), 1, "transposition");
assert.equal(levenshtein("kitten", "sitting"), 3);
const t = "Adaeze walked home. Adeaze looked back at the harbour. Marcus waited. Adaeze smiled at Tunde.";
const issues = localGuard(t, ["Adaeze", "Tunde Bello"]);
assert.equal(issues.length, 1, JSON.stringify(issues));
assert.match(issues[0].problem, /Adeaze/);
assert.match(issues[0].quote, /Adeaze looked back/);
assert.equal(localGuard("Marcus waited at the pier with Adaeze.", ["Adaeze"]).length, 0, "unrelated names are not flagged");
assert.equal(localGuard("Mara and Mark argued.", ["Mara", "Mark"]).length, 0, "two known names are not flagged against each other");
assert.ok(quoteInText("She said “hello”   there  friend.", 'said "hello" there friend'));
assert.ok(!quoteInText("She said hello.", "He never said hello at all"));
assert.ok(!quoteInText("abc", "abc"), "too-short quotes rejected");
assert.equal(hashOf("a"), hashOf("a")); assert.notEqual(hashOf("a"), hashOf("b"));
assert.match(bibleText([{ kind: "character", name: "Ada", body: "Brave" }, { kind: "rule", name: "No magic", body: "" }]), /Characters:\n- Ada: Brave[\s\S]*World rules:\n- No magic/);
