// Drives Idea Lab and Writing Tools in Chrome against a dev server started with AI_PROVIDER=mock.
import { chromium } from "playwright-core";
const B = process.env.BASE ?? "http://localhost:3111";
const results = []; const t = (n, ok, x = "") => { results.push(ok); console.log(`${ok ? "PASS" : "FAIL"} ${n}${x ? " (" + x + ")" : ""}`); };
const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--no-sandbox"] });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage();
const errors = []; page.on("pageerror", (e) => errors.push(String(e)));
await page.goto(`${B}/signup`);
await page.fill("input[name=email]", `s3ui${Date.now()}@t.io`); await page.fill("input[name=password]", "password123");
await page.click('button:has-text("Sign up")'); await page.waitForURL("**/dashboard");

await page.click('nav a:has-text("Idea Lab")'); await page.waitForURL("**/ideas");
t("generate disabled when empty", await page.locator('button:has-text("Generate suggestions")').isDisabled());
await page.fill("#idea-input", "A lighthouse keeper finds a letter meant for someone else.");
await page.click('button:has-text("Generate suggestions")');
await page.locator('article[aria-label="Result"]').waitFor();
t("refined idea shown", await page.locator("text=A refined version of the idea.").count() === 1);
t("three directions shown", await page.locator("text=Direction C.").count() === 1);
t("says suggestions only", await page.locator("text=Suggestions only").count() === 1);
await page.click('button[role=tab]:has-text("Characters")');
await page.click('button:has-text("Generate suggestions")');
await page.locator("text=Mock Name").waitFor();
t("character card shown", await page.locator("text=Fears being found out.").count() === 1);
await page.locator("text=Earlier ideas").waitFor();
await page.waitForFunction(() => [...document.querySelectorAll("section")].find((x) => x.querySelector("h2")?.textContent === "Earlier ideas")?.querySelectorAll("li").length === 2, null, { timeout: 5000 }).catch(() => {});
t("history has 2 entries", await page.locator("section:has(h2:has-text('Earlier ideas')) li").count() === 2);
await page.locator("section:has(h2:has-text('Earlier ideas')) li button:has-text('lighthouse')").last().click();
t("reopen history shows idea", await page.locator("text=Direction A.").count() === 1);
await page.locator('button[aria-label="Delete idea"]').first().click();
await page.waitForFunction(() => [...document.querySelectorAll("section")].find((x) => x.querySelector("h2")?.textContent === "Earlier ideas")?.querySelectorAll("li").length === 1);
t("delete removes entry", true);

await page.click('nav a:has-text("Writing Tools")'); await page.waitForURL("**/tools");
await page.fill('textarea[aria-label="Story context"]', "Two sisters at a funeral");
await page.fill('input[aria-label="Tone"]', "Tender");
await page.click('button:has-text("Build prompt")');
const out = page.locator('textarea[aria-label="Generated prompt"]'); await out.waitFor();
const v = await out.inputValue();
t("prompt has context and tone", v.includes("Two sisters at a funeral") && v.includes("Tone:\nTender"));
t("prompt omits empty fields", !v.includes("Pacing"));
await page.fill('input[aria-label="Prompt title"]', "Funeral scene"); await page.click('button:has-text("Save")');
await page.locator("text=Saved prompts").waitFor();
t("saved prompt listed", await page.locator("button:has-text('Funeral scene')").count() === 1);
await page.fill("#rough", "A dinner that goes wrong"); await page.click('button:has-text("Suggest fields")');
await page.waitForFunction(() => document.querySelector('textarea[aria-label="Story context"]')?.value === "Two sisters at a funeral" );
t("AI suggestion does not overwrite typed field", true);
await page.waitForFunction(() => document.querySelector('input[aria-label="Pacing"]')?.value === "Slow");
t("AI suggestion fills empty field", true);
await page.click('button[aria-label="Delete Funeral scene"]');
await page.waitForFunction(() => !document.body.innerText.includes("Saved prompts"));
t("saved prompt deleted", true);
t("no page errors", errors.length === 0, errors.join("|"));
await browser.close(); process.exit(results.every(Boolean) ? 0 : 1);
